/// Weekday
enum WeekDay(final String rrule, final String name) {
  /// Monday
  mon('MO', 'Monday'),

  /// Tuesday
  tue('TU', 'Tuesday'),

  /// Wednesday
  wed('WE', 'Wednesday'),

  /// Thursday
  thu('TH', 'Thursday'),

  /// Friday
  fri('FR', 'Friday'),

  /// Saturday
  sat('SA', 'Saturday'),

  /// Sunday
  sun('SU', 'Sunday'),
}
